export function noscriptForPage(page) {
  const links = THEME_PAGES.map(
    (theme) => `      <li><a href="${theme.path}">${escapeHtml(theme.h1)}</a></li>`,
  ).join('\n')
  const faqs = (page.faqs || HOME_FAQS)
    .map(
      (faq) => `        <div>
          <h3>${escapeHtml(faq.question)}</h3>
          <p>${escapeHtml(faq.answer)}</p>
        </div>`,
    )
    .join('\n')
  const lead = page.lead ? `        <p>${escapeHtml(page.lead)}</p>\n` : ''
  return `    <noscript>
      <main>
        <h1>${escapeHtml(page.h1)}</h1>
${lead}        <p>${escapeHtml(page.description)}</p>
        <p><a href="/make/">Try now</a> · <a href="/docs/">API docs</a> · <a href="/pricing/">Pricing</a> · <a href="/account/">Account</a></p>
        <h2>Layouts ready to post</h2>
        <ul>
${links}
        </ul>
        <h2>Frequently asked questions</h2>
${faqs}
      </main>
    </noscript>`
}

export function sitemapXml(lastmod = new Date().toISOString().slice(0, 10)) {
  const extra = [
    ...MARKETING_EXTRA_PAGES,
    { path: '/privacy', changefreq: 'yearly', priority: '0.3' },
    { path: '/terms', changefreq: 'yearly', priority: '0.3' },
  ]
  const urls = [...INDEXABLE_PAGES, ...extra].map(
    (page) => `  <url>
    <loc>${page.path === '/privacy' || page.path === '/terms' ? `${SITE.origin}${page.path}` : absoluteUrl(page.path)}</loc>
    <lastmod>${lastmod}</lastmod>
    <changefreq>${page.changefreq}</changefreq>
    <priority>${page.priority}</priority>
  </url>`,
  ).join('\n')
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
`
}

