export function isProTheme(themeOrId) {
  if (!themeOrId) return false
  if (typeof themeOrId === 'string') return PRO_THEME_IDS.has(themeOrId)
  return Boolean(themeOrId.pro) || PRO_THEME_IDS.has(themeOrId.id)
}

